using System;
using System.IO;
using NUnit.Framework;
using UnityEditor;
using UnityEngine;
using Object = UnityEngine.Object;

namespace Soulvail.Tests.Game.Views;

/// <summary>
/// The circle every telegraph ring is drawn with. The PNG is read from disk rather than through the
/// importer, so the rows see the pixels the generator wrote and not a compressed copy.
/// </summary>
[TestFixture]
public sealed class TelegraphRingTextureTests
{
    private const string MaskPath = "Assets/_Project/Art/Vfx/T_TelegraphRing_Mask.png";
    private const string MaterialPath = "Assets/_Project/Materials/M_TelegraphRing.mat";
    private const int Size = 256;

    private Texture2D _mask;

    [SetUp]
    public void SetUp()
    {
        Assert.That(File.Exists(MaskPath), Is.True, "the mask is generated by Soulvail/VFX/Generate Telegraph Ring Mask");
        _mask = new Texture2D(2, 2, TextureFormat.RGBA32, false);
        Assert.That(_mask.LoadImage(File.ReadAllBytes(MaskPath)), Is.True);
        Assert.That(_mask.width, Is.EqualTo(Size));
        Assert.That(_mask.height, Is.EqualTo(Size));
    }

    [TearDown]
    public void TearDown() => Object.DestroyImmediate(_mask);

    /// <summary>Alpha at a point given in texels from the centre.</summary>
    private float AlphaAt(float dx, float dy) =>
        _mask.GetPixel(Mathf.FloorToInt(Size * 0.5f + dx), Mathf.FloorToInt(Size * 0.5f + dy)).a;

    [Test]
    public void RingMask_IsInscribedCircle()
    {
        Assert.That(_mask.GetPixel(0, 0).a, Is.EqualTo(0f));
        Assert.That(_mask.GetPixel(Size - 1, 0).a, Is.EqualTo(0f));
        Assert.That(_mask.GetPixel(0, Size - 1).a, Is.EqualTo(0f));
        Assert.That(_mask.GetPixel(Size - 1, Size - 1).a, Is.EqualTo(0f));
        Assert.That(AlphaAt(0f, 0f), Is.GreaterThanOrEqualTo(0.4f));

        for (int i = 0; i < 8; i++)
        {
            float angle = i * Mathf.PI / 4f + 0.1f;
            var dir = new Vector2(Mathf.Cos(angle), Mathf.Sin(angle));

            // Walk outwards from inside the rim, in quarter-texel steps, to the first point under 50 % alpha.
            float edge = -1f;
            for (float r = Size * 0.47f; r < Size * 0.5f * 1.5f; r += 0.25f)
            {
                if (AlphaAt(dir.x * r, dir.y * r) < 0.5f)
                {
                    edge = r;
                    break;
                }
            }

            Assert.That(edge, Is.EqualTo(Size * 0.5f).Within(1.5f), $"ray {i}");
        }
    }

    [Test]
    public void RingMask_RimIsBrighter()
    {
        float radius = Size * 0.5f;
        for (int i = 0; i < 8; i++)
        {
            float angle = i * Mathf.PI / 4f + 0.3f;
            var dir = new Vector2(Mathf.Cos(angle), Mathf.Sin(angle));
            Assert.That(AlphaAt(dir.x * radius * 0.96f, dir.y * radius * 0.96f), Is.EqualTo(1f).Within(0.01f), $"rim {i}");
            Assert.That(AlphaAt(dir.x * radius * 0.5f, dir.y * radius * 0.5f), Is.EqualTo(0.45f).Within(0.01f), $"fill {i}");
        }
    }

    [Test]
    public void RingMask_IsWhite()
    {
        Color32[] pixels = _mask.GetPixels32();
        foreach (Color32 p in pixels)
        {
            if (p.a == 0)
            {
                continue;
            }

            Assert.That(p.r, Is.EqualTo(255));
            Assert.That(p.g, Is.EqualTo(255));
            Assert.That(p.b, Is.EqualTo(255));
        }
    }

    [Test]
    public void RingMask_ImportSettings()
    {
        var importer = (TextureImporter)AssetImporter.GetAtPath(MaskPath);
        Assert.That(importer, Is.Not.Null);
        Assert.That(importer.wrapMode, Is.EqualTo(TextureWrapMode.Clamp));
        Assert.That(importer.filterMode, Is.EqualTo(FilterMode.Bilinear));
        Assert.That(importer.mipmapEnabled, Is.True);
        Assert.That(importer.alphaIsTransparency, Is.True);

        TextureImporterPlatformSettings android = importer.GetPlatformTextureSettings("Android");
        Assert.That(android.overridden, Is.True);
        Assert.That(android.format, Is.EqualTo(TextureImporterFormat.ASTC_6x6));
    }

    [Test]
    public void RingMaterial_SamplesTheMask()
    {
        var material = AssetDatabase.LoadAssetAtPath<Material>(MaterialPath);
        var mask = AssetDatabase.LoadAssetAtPath<Texture2D>(MaskPath);
        Assert.That(material, Is.Not.Null);
        Assert.That(mask, Is.Not.Null);
        Assert.That(material.GetTexture("_BaseMap"), Is.EqualTo(mask));

        // The blend state and queue are the ones the five decals already share.
        Assert.That(material.GetFloat("_Surface"), Is.EqualTo(1f));
        Assert.That(material.GetFloat("_SrcBlend"), Is.EqualTo(5f));
        Assert.That(material.GetFloat("_DstBlend"), Is.EqualTo(10f));
        Assert.That(material.GetFloat("_ZWrite"), Is.EqualTo(0f));
        Assert.That(material.renderQueue, Is.EqualTo(3000));
    }
}
